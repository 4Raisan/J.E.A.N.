//! Proof that the transport verifies certificates, rather than merely configuring itself to.
//!
//! Every other `https` assertion in this crate is negative — a plaintext server refused, a flag
//! that stays off. None of them shows a handshake *succeeding* because of a certificate chain,
//! which is the claim `model.base_url = "https://…"` actually makes. This file supplies the cases
//! that sentence needs, against a real TLS server on loopback:
//!
//! | server certificate | dialed name | pinned anchor | expected |
//! |---|---|---|---|
//! | `leaf-localhost` (CA A) | `localhost` | CA A | accepted |
//! | `leaf-localhost` (CA A) | `127.0.0.1` | CA A | rejected: the name is not in the certificate |
//! | `leaf-other-host` (CA A) | `localhost` | CA A | rejected: a different, unrelated name |
//! | `leaf-untrusted-ca-b` (CA B) | `localhost` | CA A | rejected: the chain reaches no trusted root |
//! | `leaf-untrusted-ca-b` (CA B) | `localhost` | CA B | accepted: same server, one input changed |
//!
//! Every row is the same harness, the same port shape and the same request; only the certificate,
//! the dialed name, or the anchor differs. The two accepted rows are what make the three rejected
//! rows mean something: without them a broken test server would also produce three rejections, and
//! "rejected" would be evidence of nothing.
//!
//! Nothing here touches a trust store on this machine. The client is handed one CA DER through
//! `agent_config`'s anchor argument, which makes that CA the *only* root the connection may build
//! to, and `disable_verification` is never set — so the chain check and the name check both run,
//! exactly as they do in a shipped build.
//!
//! The fixtures are throwaway and generated by `tests/fixtures/tls/generate.sh`, which says why each
//! certificate exists. If a test here cannot find its fixture, run that script; the certificates are
//! signed out to mid-2040, so an expired one is not something a maintenance window will hide.

use std::io::{Read, Write};
use std::net::{TcpListener, TcpStream};
use std::path::Path;
use std::sync::atomic::{AtomicBool, Ordering};
use std::sync::{Arc, Mutex};
use std::time::{Duration, Instant};

use native_tls::{Identity, TlsAcceptor, TlsStream};

use crate::error::ModelError;
use crate::http::{self, OutgoingRequest, RawResponse, Target};

/// How long the server thread keeps trying to answer, so an unclaimed port cannot strand it.
const SERVER_LIFETIME: Duration = Duration::from_secs(10);

/// How long one socket operation inside that thread may block.
///
/// Generous, because the server's handshake read waits while the client validates the chain, and a
/// budget short enough to expire there aborts a *valid* handshake — which would make the three
/// rejected rows below pass for the wrong reason. The two accepted rows are what catch that, which
/// is the whole reason they exist.
const SOCKET_BUDGET: Duration = Duration::from_secs(5);

/// The client deadline. Deliberately generous: the assertion is the outcome, not the clock, and on
/// this stack a refused handshake has been measured taking a couple of seconds to surface.
const CLIENT_TIMEOUT: Duration = Duration::from_secs(20);

fn fixture(name: &str) -> Vec<u8> {
    let path = Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("tests/fixtures/tls")
        .join(name);
    std::fs::read(&path).unwrap_or_else(|error| {
        panic!(
            "cannot read {}: {error}\nregenerate the fixtures with \
             `bash crates/jean-model/tests/fixtures/tls/generate.sh`",
            path.display()
        )
    })
}

/// A leaf's PKCS#12 bundle, by fixture stem.
///
/// PKCS#12 and not PEM: `native_tls::Identity::from_pkcs8` on Windows associates the key with
/// `KeySpec::key_exchange()`, and Schannel then refuses the credential with SEC_E_NO_CREDENTIALS.
/// That was found by measuring, not by reading — the first version of this file used the PEM form
/// and every handshake failed, which made the three "rejected" rows pass for the wrong reason.
fn identity(name: &str) -> Vec<u8> {
    fixture(&format!("{name}.pfx"))
}

/// The password in `generate.sh`. It protects a throwaway test key, so it is written here plainly
/// rather than read from a secret source.
const IDENTITY_PASSWORD: &str = "jean-test";

/// Push one line into the worker's account, if the log is still reachable at all. A diagnostic that
/// can itself panic on a poisoned lock is worse than the silence it replaces.
fn record(log: &Arc<Mutex<Vec<String>>>, line: String) {
    if let Ok(mut observed) = log.lock() {
        observed.push(line);
    }
}

/// A TLS server that answers exactly one request, on an ephemeral loopback port.
///
/// `answered` is set only after a handshake completed *and* the response was written, so `false`
/// after a client attempt means the client never got as far as HTTP.
///
/// `observed` is what the worker thread saw. From the client's side a certificate it correctly
/// refused and a test harness that never managed to complete a handshake look like the same
/// connection reset, so the accepted rows quote the server's own account when they fail.
struct TlsServer {
    port: u16,
    answered: Arc<AtomicBool>,
    observed: Arc<Mutex<Vec<String>>>,
}

impl TlsServer {
    fn spawn(bundle: &[u8]) -> Self {
        let identity =
            Identity::from_pkcs12(bundle, IDENTITY_PASSWORD).expect("import the fixture identity");
        // Built on the calling thread on purpose. An acceptor that cannot be constructed must fail
        // the test that is about to claim a rejection, not park in a worker thread where the three
        // rejected rows of the table above would pass for the wrong reason.
        let acceptor = TlsAcceptor::new(identity).expect("build a test TLS acceptor");
        let listener = TcpListener::bind("127.0.0.1:0").expect("bind a loopback port");
        let port = listener.local_addr().expect("the ephemeral port").port();
        // Non-blocking so the thread can notice its own deadline instead of parking in `accept`.
        listener
            .set_nonblocking(true)
            .expect("put the listener in non-blocking mode");

        let answered = Arc::new(AtomicBool::new(false));
        let worker_flag = answered.clone();
        let observed = Arc::new(Mutex::new(Vec::new()));
        let worker_log = observed.clone();
        std::thread::spawn(move || {
            let deadline = Instant::now() + SERVER_LIFETIME;
            while Instant::now() < deadline {
                let (stream, _) = match listener.accept() {
                    Ok(pair) => pair,
                    Err(error) if error.kind() == std::io::ErrorKind::WouldBlock => {
                        std::thread::sleep(Duration::from_millis(5));
                        continue;
                    }
                    Err(_) => return,
                };
                // A socket off a non-blocking listener is itself non-blocking; the handshake and
                // the request read want a blocking socket with a bound on it.
                let _ = stream.set_nonblocking(false);
                let _ = stream.set_read_timeout(Some(SOCKET_BUDGET));
                let _ = stream.set_write_timeout(Some(SOCKET_BUDGET));
                let mut tls = match acceptor.accept(stream) {
                    Ok(tls) => tls,
                    // The client refused this certificate and hung up. For the rejected rows that
                    // is the expected outcome, so it is recorded rather than reported.
                    Err(error) => {
                        record(&worker_log, format!("handshake not completed: {error}"));
                        continue;
                    }
                };
                read_request(&mut tls);
                if write_answer(&mut tls) {
                    worker_flag.store(true, Ordering::Relaxed);
                    record(
                        &worker_log,
                        "handshake completed and answer written".to_owned(),
                    );
                    return;
                }
                record(
                    &worker_log,
                    "handshake completed but the answer was not written".to_owned(),
                );
            }
        });

        Self {
            port,
            answered,
            observed,
        }
    }

    /// The worker thread's account, for a failure message.
    ///
    /// The worker writes asynchronously and the client gives up first, so this waits a moment
    /// rather than reporting an empty log as though nothing had happened.
    fn observed(&self) -> String {
        for _ in 0..25 {
            match self.observed.lock() {
                Ok(log) if !log.is_empty() => return log.join(" / "),
                Err(_) => return "the worker thread panicked".to_owned(),
                Ok(_) => std::thread::sleep(Duration::from_millis(10)),
            }
        }
        "nothing: no connection ever reached the TLS layer".to_owned()
    }

    /// This server as the model client would be configured to reach it, under `host`.
    fn target(&self, host: &str) -> Target {
        Target::parse(&format!("https://{host}:{}", self.port)).expect("parse the test endpoint")
    }
}

/// How much of a request body this stub will wait for, and the most head it will hold.
const REQUEST_BOUND: usize = 64 * 1024;

/// Read the request — head and body.
///
/// The body arrives in its own TLS record after the head, and a socket closed with bytes still
/// unread sends an RST instead of a FIN. That reset reaches the client before the response it was
/// waiting for, and the client reports it as a connection failure *on a handshake that already
/// succeeded*. Draining is therefore part of the harness, not a detail: the first version of this
/// function stopped at the header terminator and every accepted row failed with os error 10054.
fn read_request(tls: &mut TlsStream<TcpStream>) {
    let mut buf: Vec<u8> = Vec::new();
    let mut chunk = [0u8; 1024];
    let head_end = loop {
        let read = match tls.read(&mut chunk) {
            Ok(n) if n > 0 => n,
            _ => return,
        };
        buf.extend_from_slice(&chunk[..read]);
        if let Some(at) = buf.windows(4).position(|head| head == b"\r\n\r\n") {
            break at + 4;
        }
        if buf.len() >= REQUEST_BOUND {
            return;
        }
    };
    let declared = String::from_utf8_lossy(&buf[..head_end])
        .to_ascii_lowercase()
        .lines()
        .find_map(|line| line.strip_prefix("content-length:"))
        .and_then(|value| value.trim().parse::<usize>().ok())
        .unwrap_or(0)
        .min(REQUEST_BOUND);
    while buf.len() < head_end + declared {
        match tls.read(&mut chunk) {
            Ok(0) | Err(_) => return,
            Ok(n) => buf.extend_from_slice(&chunk[..n]),
        }
    }
}

fn write_answer(tls: &mut TlsStream<TcpStream>) -> bool {
    const BODY: &str = r#"{"schema_version":1}"#;
    let head = format!(
        "HTTP/1.1 200 OK\r\ncontent-type: application/json\r\ncontent-length: {}\r\n\
         connection: close\r\n\r\n",
        BODY.len()
    );
    tls.write_all(head.as_bytes()).is_ok()
        && tls.write_all(BODY.as_bytes()).is_ok()
        && tls.flush().is_ok()
}

fn post() -> OutgoingRequest {
    OutgoingRequest {
        method: "POST",
        path: "/api/chat".to_owned(),
        headers: vec![(
            "authorization".to_owned(),
            "Bearer fixture-client-secret".to_owned(),
        )],
        body: br#"{"prompt":"hello"}"#.to_vec(),
        timeout: CLIENT_TIMEOUT,
        max_response_bytes: 64 * 1024,
    }
}

/// One attempt: this certificate set on the server, this name dialed, this authority pinned.
fn attempt(server: &TlsServer, host: &str, anchor: &str) -> Result<RawResponse, ModelError> {
    let cancel = AtomicBool::new(false);
    http::send_test_anchored(&server.target(host), &post(), &cancel, &fixture(anchor))
}

/// The shape every rejection in this file must have: no HTTP was ever exchanged, the failure is a
/// transport failure rather than a status, a body, or an empty plan, and Schannel's own sentence
/// names the check that refused.
///
/// The third part is not decoration. While the harness itself was broken the client reported a
/// connection reset with no certificate sentence at all, and the two tests that now pass on
/// `"not trusted"` and `"does not match"` would have gone on passing for the wrong reason.
fn refused(error: ModelError, server: &TlsServer, because: &str) {
    assert!(
        !server.answered.load(Ordering::Relaxed),
        "the server answered a client that should have refused it: {error}"
    );
    assert!(
        matches!(error, ModelError::Connect { .. } | ModelError::Protocol(_)),
        "a refused certificate must fail before any HTTP result exists, got {error}"
    );
    let text = error.to_string();
    assert!(
        text.contains(because),
        "the refusal must name the check that produced it ({because:?}), got {text}"
    );
}

/// The handshake succeeded, the certificate was verified against the pinned authority, and the
/// answer came back — over TLS, not around it.
#[test]
fn a_trusted_certificate_for_the_right_name_completes_the_handshake_and_answers() {
    let bundle = identity("leaf-localhost");
    let server = TlsServer::spawn(&bundle);
    let answer = attempt(&server, "localhost", "ca-a.der").unwrap_or_else(|error| {
        panic!(
            "a leaf signed by the pinned CA and valid for `localhost` must be accepted; \
             the client said {error}; the server said {}",
            server.observed()
        )
    });
    assert_eq!(answer.status, 200);
    assert_eq!(answer.body_text(), r#"{"schema_version":1}"#);
    assert!(
        server.answered.load(Ordering::Relaxed),
        "the response must have been written on the TLS connection, not on a plain socket"
    );
}

/// The same trusted certificate, dialed by an address it does not list, is refused.
///
/// Nothing about the chain changes between this test and the one above — only the name the request
/// was sent to. That isolates the hostname check from the chain check.
#[test]
fn a_trusted_certificate_is_refused_when_the_dialed_host_is_not_in_it() {
    let bundle = identity("leaf-localhost");
    let server = TlsServer::spawn(&bundle);
    let error = attempt(&server, "127.0.0.1", "ca-a.der")
        .expect_err("this leaf names `localhost`, not this address, so it must not be accepted");
    refused(error, &server, "does not match");
}

/// A different name, under the same trusted authority.
#[test]
fn a_certificate_for_another_host_name_is_rejected() {
    let bundle = identity("leaf-other-host");
    let server = TlsServer::spawn(&bundle);
    let error = attempt(&server, "localhost", "ca-a.der")
        .expect_err("this leaf is valid for `other.invalid`, and the authority is not the excuse");
    refused(error, &server, "does not match");
}

/// A chain that reaches no trusted root is refused even when the name matches perfectly.
#[test]
fn a_certificate_that_does_not_chain_to_a_trusted_authority_is_rejected() {
    let bundle = identity("leaf-untrusted-ca-b");
    let server = TlsServer::spawn(&bundle);
    let error = attempt(&server, "localhost", "ca-a.der")
        .expect_err("CA B is not an anchor, so this must not be accepted");
    refused(error, &server, "not trusted");
}

/// The control for the test above: this server, this name, this request — with CA B as the anchor
/// the handshake completes. Without it, an untrusted-chain rejection could just as well mean the
/// harness never worked.
#[test]
fn the_untrusted_fixture_is_accepted_once_its_own_authority_is_pinned() {
    let bundle = identity("leaf-untrusted-ca-b");
    let server = TlsServer::spawn(&bundle);
    let answer = attempt(&server, "localhost", "ca-b.der").unwrap_or_else(|error| {
        panic!(
            "the same certificate is trusted the moment its own CA is the anchor; \
             the client said {error}; the server said {}",
            server.observed()
        )
    });
    assert_eq!(answer.status, 200);
    assert!(
        server.answered.load(Ordering::Relaxed),
        "the control handshake must really have completed"
    );
}
